import { useEffect, useMemo, useState } from "react";
import { useNavigate } from "react-router-dom";
import api from "../services/api";

export default function Cases() {
  const navigate = useNavigate();

  const [cases, setCases] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const [search, setSearch] = useState("");
  const [priority, setPriority] = useState("");
  const [status, setStatus] = useState("");

  const [page, setPage] = useState(1);

  const PAGE_SIZE = 10;

  useEffect(() => {
    loadCases();
  }, []);

  const loadCases = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await api.get("/cases");

      setCases(response.data.cases || []);
    } catch (err) {
      console.error("Failed to load cases:", err);

      setError(
        err?.response?.data?.detail ||
          "Unable to load investigation cases."
      );
    } finally {
      setLoading(false);
    }
  };

  const filteredCases = useMemo(() => {
    const searchValue = search.trim().toLowerCase();

    return cases.filter((item) => {
      const matchesSearch =
        !searchValue ||
        String(item.case_id || "")
          .toLowerCase()
          .includes(searchValue) ||
        String(item.alert_id || "")
          .toLowerCase()
          .includes(searchValue) ||
        String(item.transaction_id || "")
          .toLowerCase()
          .includes(searchValue) ||
        String(item.sender_account || "")
          .toLowerCase()
          .includes(searchValue) ||
        String(item.receiver_account || "")
          .toLowerCase()
          .includes(searchValue);

      const matchesPriority =
        !priority ||
        String(item.case_priority || "").toUpperCase() ===
          priority;

      const matchesStatus =
        !status ||
        String(item.case_status || "").toUpperCase() ===
          status;

      return (
        matchesSearch &&
        matchesPriority &&
        matchesStatus
      );
    });
  }, [cases, search, priority, status]);

  const totalPages = Math.max(
    1,
    Math.ceil(filteredCases.length / PAGE_SIZE)
  );

  const currentPage = Math.min(page, totalPages);

  const paginatedCases = useMemo(() => {
    const start =
      (currentPage - 1) * PAGE_SIZE;

    return filteredCases.slice(
      start,
      start + PAGE_SIZE
    );
  }, [filteredCases, currentPage]);

  useEffect(() => {
    setPage(1);
  }, [search, priority, status]);

  const formatAmount = (amount) => {
    const value = Number(amount);

    if (!Number.isFinite(value)) {
      return "—";
    }

    return new Intl.NumberFormat("en-IN", {
      style: "currency",
      currency: "INR",
      maximumFractionDigits: 2,
    }).format(value);
  };

  const formatTimestamp = (timestamp) => {
    if (!timestamp) {
      return "—";
    }

    const date = new Date(timestamp);

    if (Number.isNaN(date.getTime())) {
      return timestamp;
    }

    return date.toLocaleString("en-IN", {
      day: "2-digit",
      month: "short",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  };

  const formatRiskScore = (score) => {
    const value = Number(score);

    if (!Number.isFinite(value)) {
      return "—";
    }

    return value.toFixed(3);
  };

  const formatTypology = (typology) => {
    if (!typology) {
      return "Normal";
    }

    return String(typology)
      .replaceAll("_", " ")
      .replace(/\b\w/g, (char) => char.toUpperCase());
  };

  const clearFilters = () => {
    setSearch("");
    setPriority("");
    setStatus("");
  };

  const openCase = (caseItem) => {
        const alertId = String(
            caseItem?.alert_id || ""
        ).trim();

        if (!alertId) {
            console.error(
            "Cannot open case: missing alert_id",
            caseItem
            );
            return;
        }

        console.log(
            "Opening investigation workspace:",
            alertId
        );

        navigate(`/workspace/${alertId}`);
    };

  return (
    <section className="cases-page">

      {/* PAGE HEADER */}
      <div className="page-header">

        <div>
          <div className="page-eyebrow">
            INVESTIGATION
          </div>

          <h1>Cases</h1>

          <p>
            Review and investigate financial crime
            cases generated by the detection pipeline.
          </p>
        </div>

        <div className="cases-header-stat">
          <span className="cases-header-stat-label">
            TOTAL CASES
          </span>

          <strong>
            {cases.length.toLocaleString("en-IN")}
          </strong>
        </div>

      </div>

      {/* SUMMARY CARDS */}
      <div className="cases-summary-grid">

        <div className="cases-summary-card">

          <span className="cases-summary-label">
            HIGH PRIORITY
          </span>

          <strong>
            {
              cases.filter(
                (item) =>
                  String(item.case_priority)
                    .toUpperCase() === "HIGH"
              ).length
            }
          </strong>

          <span className="cases-summary-description">
            Cases requiring immediate attention
          </span>

        </div>

        <div className="cases-summary-card">

          <span className="cases-summary-label">
            MEDIUM PRIORITY
          </span>

          <strong>
            {
              cases.filter(
                (item) =>
                  String(item.case_priority)
                    .toUpperCase() === "MEDIUM"
              ).length
            }
          </strong>

          <span className="cases-summary-description">
            Cases requiring investigation
          </span>

        </div>

        <div className="cases-summary-card">

          <span className="cases-summary-label">
            OPEN
          </span>

          <strong>
            {
              cases.filter(
                (item) =>
                  String(item.case_status)
                    .toUpperCase() === "OPEN"
              ).length
            }
          </strong>

          <span className="cases-summary-description">
            Active investigation cases
          </span>

        </div>

        <div className="cases-summary-card">

          <span className="cases-summary-label">
            FRAUD-LINKED
          </span>

          <strong>
            {
              cases.filter(
                (item) =>
                  Number(item.is_fraud) === 1
              ).length
            }
          </strong>

          <span className="cases-summary-description">
            Cases linked to fraud ground truth
          </span>

        </div>

      </div>

      {/* FILTERS */}
      <div className="cases-filter-panel">

        <div className="cases-search">

          <label htmlFor="case-search">
            Search
          </label>

          <input
            id="case-search"
            type="text"
            placeholder="Case, alert, transaction or account..."
            value={search}
            onChange={(event) =>
              setSearch(event.target.value)
            }
          />

        </div>

        <div className="cases-filter">

          <label htmlFor="case-priority">
            Priority
          </label>

          <select
            id="case-priority"
            value={priority}
            onChange={(event) =>
              setPriority(event.target.value)
            }
          >
            <option value="">
              All priorities
            </option>

            <option value="HIGH">
              High
            </option>

            <option value="MEDIUM">
              Medium
            </option>

            <option value="LOW">
              Low
            </option>
          </select>

        </div>

        <div className="cases-filter">

          <label htmlFor="case-status">
            Status
          </label>

          <select
            id="case-status"
            value={status}
            onChange={(event) =>
              setStatus(event.target.value)
            }
          >
            <option value="">
              All statuses
            </option>

            <option value="OPEN">
              Open
            </option>

            <option value="CLOSED">
              Closed
            </option>

            <option value="ESCALATED">
              Escalated
            </option>
          </select>

        </div>

        <button
          type="button"
          className="cases-clear-button"
          onClick={clearFilters}
        >
          Clear
        </button>

      </div>

      {/* CASE CONTENT */}
      <div className="cases-card">

        {loading && (
          <div className="cases-state">

            <div className="cases-spinner" />

            <p>
              Loading investigation cases...
            </p>

          </div>
        )}

        {!loading && error && (
          <div className="cases-state cases-error">

            <div className="cases-state-icon">
              !
            </div>

            <h3>
              Unable to load cases
            </h3>

            <p>{error}</p>

            <button
              type="button"
              onClick={loadCases}
            >
              Retry
            </button>

          </div>
        )}

        {!loading &&
          !error &&
          filteredCases.length === 0 && (
            <div className="cases-state">

              <div className="cases-state-icon">
                —
              </div>

              <h3>
                No cases found
              </h3>

              <p>
                Try changing the current filters.
              </p>

            </div>
          )}

        {!loading &&
          !error &&
          filteredCases.length > 0 && (
            <>
              <div className="cases-table-wrapper">

                <table className="cases-table">

                  <thead>
                    <tr>
                      <th>Case</th>
                      <th>Priority</th>
                      <th>Status</th>
                      <th>Risk</th>
                      <th>Transaction</th>
                      <th>Accounts</th>
                      <th>Amount</th>
                      <th>Typology</th>
                      <th>Created</th>
                      <th></th>
                    </tr>
                  </thead>

                  <tbody>

                    {paginatedCases.map((caseItem) => {

                      const priorityValue =
                        String(
                          caseItem.case_priority || ""
                        ).toLowerCase();

                      const statusValue =
                        String(
                          caseItem.case_status || ""
                        ).toLowerCase();

                      const riskValue =
                        String(
                          caseItem.risk_category || ""
                        ).toLowerCase();

                      return (
                        <tr
                          key={caseItem.case_id}
                        >

                          <td>

                            <div className="case-id-cell">

                              <strong>
                                {caseItem.case_id}
                              </strong>

                              <span>
                                {caseItem.alert_id}
                              </span>

                            </div>

                          </td>

                          <td>

                            <span
                              className={`case-priority case-priority-${priorityValue}`}
                            >
                              {caseItem.case_priority ||
                                "—"}
                            </span>

                          </td>

                          <td>

                            <span
                              className={`case-status case-status-${statusValue}`}
                            >
                              {caseItem.case_status ||
                                "—"}
                            </span>

                          </td>

                          <td>

                            <div className="case-risk-cell">

                              <strong>
                                {formatRiskScore(
                                  caseItem.risk_score
                                )}
                              </strong>

                              <span
                                className={`case-risk-category case-risk-${riskValue}`}
                              >
                                {caseItem.risk_category ||
                                  "—"}
                              </span>

                            </div>

                          </td>

                          <td>

                            <span className="case-transaction-id">
                              {caseItem.transaction_id}
                            </span>

                          </td>

                          <td>

                            <div className="case-account-cell">

                              <span>
                                {caseItem.sender_account}
                              </span>

                              <span className="case-account-arrow">
                                →
                              </span>

                              <span>
                                {caseItem.receiver_account}
                              </span>

                            </div>

                          </td>

                          <td>

                            <strong className="case-amount">
                              {formatAmount(
                                caseItem.amount
                              )}
                            </strong>

                          </td>

                          <td>

                            <span className="case-typology">
                              {formatTypology(
                                caseItem.typology
                              )}
                            </span>

                          </td>

                          <td>

                            <span className="case-timestamp">
                              {formatTimestamp(
                                caseItem.timestamp
                              )}
                            </span>

                          </td>

                          <td>

                            <button
                              type="button"
                              className="case-investigate-button"
                              onClick={(event) => {
                                    event.stopPropagation();
                                    openCase(caseItem);
                                }}
                            >
                              Investigate
                            </button>

                          </td>

                        </tr>
                      );
                    })}

                  </tbody>

                </table>

              </div>

              {/* PAGINATION */}
              <div className="cases-pagination">

                <div className="cases-pagination-info">

                  Showing{" "}
                  <strong>
                    {filteredCases.length === 0
                      ? 0
                      : (currentPage - 1) *
                          PAGE_SIZE +
                        1}
                  </strong>{" "}
                  –{" "}
                  <strong>
                    {Math.min(
                      currentPage * PAGE_SIZE,
                      filteredCases.length
                    )}
                  </strong>{" "}
                  of{" "}
                  <strong>
                    {filteredCases.length}
                  </strong>

                </div>

                <div className="cases-pagination-controls">

                  <button
                    type="button"
                    disabled={currentPage <= 1}
                    onClick={() =>
                      setPage(currentPage - 1)
                    }
                  >
                    Previous
                  </button>

                  <span>
                    Page{" "}
                    <strong>
                      {currentPage}
                    </strong>{" "}
                    of{" "}
                    <strong>
                      {totalPages}
                    </strong>
                  </span>

                  <button
                    type="button"
                    disabled={
                      currentPage >= totalPages
                    }
                    onClick={() =>
                      setPage(currentPage + 1)
                    }
                  >
                    Next
                  </button>

                </div>

              </div>
            </>
          )}

      </div>

    </section>
  );
}